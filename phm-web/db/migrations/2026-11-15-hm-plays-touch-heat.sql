-- ============================================================
-- hm_plays 增加 touch_heat（8×8 落点热度图）
--
-- 【为什么存 base64 文本而不是 bytea】
--   · 只有 64 字节，base64 后 88 字符 —— 存 text 和 bytea 的空间差异可以忽略
--   · 查询时能直接在 psql 里看（bytea 要 encode(...,'base64') 才可读）
--   · PostgreSQL 的 bytea 走 pg 驱动会有 Buffer 转换，多一层噪音
--
-- 【为什么只有 64 个格】
--   完整触控轨迹一局几万个点，存不下也没人分析。8×8 能回答的问题是：
--     · 主要按上半区还是下半区（读谱习惯）
--     · 是否偏一侧（左右手优势）
--     · 某个区域是否普遍偏早（需要 JOIN 判定数据）
--   每个格子归一化到 0..255，形状比绝对次数重要 —— 所以丢掉了原始计数。
--
-- 【null 的语义】
--   null = 纯键盘玩法（没有触控事件）或旧客户端。
--   空字符串是无效值，服务端应该拒收（见 validatePlay）。
--
-- 【为什么用 text 而不是 jsonb】
--   它是 64 字节的**不透明二进制**，不是一个可查询的结构。
--   用 jsonb 要存 64 个数组元素，反而更占空间、更难还原。
--   分析时客户端/脚本解码即可。
-- ============================================================

alter table hm_plays
  add column if not exists touch_heat text;

comment on column hm_plays.touch_heat is
  'base64(8×8 触控落点热度图, 64 字节, 每格归一化到 0..255)。null = 键盘玩法或旧客户端。';
